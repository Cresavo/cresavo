# Cresavo promo v5 — music bed, fully synthesized in code (numpy/scipy only).
# No samples, no loops, no downloaded audio, no AI/music services. Every sound below is
# built from sine/saw oscillators and filtered white noise generated by numpy.
# Writes out/_music.wav (48 kHz, 16-bit stereo), starting at film t=0, on the film's beat grid.
import json, os
import numpy as np
from scipy import signal
from scipy.io import wavfile

ROOT = os.path.dirname(os.path.abspath(__file__))
evp = os.path.join(ROOT, 'out', 'events.json')
if not os.path.exists(evp): evp = os.path.join(ROOT, 'ref', 'v4-out', 'events.json')
ev = json.load(open(evp))
SR = 48000
P = ev.get('period', 0.491971875)          # same beat period as v4 (film beat 0 = t 0)
T = ev['T'] + 0.3
N = int(T * SR)
rng = np.random.default_rng(2026)
L = np.zeros(N); R = np.zeros(N)
def bt(b): return b * P
def put(x, t0, g=1.0, pan=0.0):
    i = int(round(t0 * SR));
    if i >= N: return
    n = min(len(x), N - i)
    L[i:i+n] += x[:n] * g * np.sqrt(0.5 * (1 - pan)) * 1.414
    R[i:i+n] += x[:n] * g * np.sqrt(0.5 * (1 + pan)) * 1.414
def tt(d): return np.arange(int(d * SR)) / SR
def bp(x, lo, hi): b, a = signal.butter(2, [lo/(SR/2), hi/(SR/2)], 'band'); return signal.lfilter(b, a, x)
def hp(x, f): b, a = signal.butter(2, f/(SR/2), 'high'); return signal.lfilter(b, a, x)
def lp(x, f): b, a = signal.butter(2, f/(SR/2)); return signal.lfilter(b, a, x)
def saw(f, t, ph=0.0): return 2 * ((f * t + ph) % 1.0) - 1
def mtof(m): return 440.0 * 2 ** ((m - 69) / 12)

# ---- instruments ----
def kick():
    t = tt(0.42); f = 46 + 120 * np.exp(-t / 0.035)
    x = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.16)
    return np.tanh(1.6 * x) * 0.9 + 0.08 * hp(rng.standard_normal(len(t)), 3000) * np.exp(-t / 0.003)
def hat(open_=False):
    d = 0.22 if open_ else 0.05; t = tt(d)
    return hp(rng.standard_normal(len(t)), 7000) * np.exp(-t / (0.06 if open_ else 0.012))
def clap():
    t = tt(0.3); x = bp(rng.standard_normal(len(t)), 900, 4200)
    e = sum(np.exp(-np.clip(t - o, 0, None) / 0.006) * (t >= o) for o in (0, 0.011, 0.022)) * 0.5 + np.exp(-t / 0.09) * 0.6
    return x * e
def bass(m, d):
    t = tt(d); f = mtof(m)
    x = np.sin(2 * np.pi * f * t) + 0.25 * np.sin(2 * np.pi * 2 * f * t)
    return x * np.clip(t / 0.006, 0, 1) * np.exp(-t / (d * 0.7)) * np.clip((d - t) / 0.02, 0, 1)
def pad(notes, d, bright=1.0):
    t = tt(d); x = np.zeros(len(t)); y = np.zeros(len(t))
    for m in notes:
        f = mtof(m)
        for det, side in ((-0.11, -1), (0.0, 0), (0.12, 1)):
            s = saw(f * 2 ** (det / 12), t, rng.random())
            if side <= 0: x += s
            if side >= 0: y += s
    att = np.clip(t / 0.35, 0, 1); rel = np.clip((d - t) / 0.6, 0, 1)
    cut = 900 + 1500 * bright
    return lp(x, cut) * att * rel / len(notes), lp(y, cut) * att * rel / len(notes)
def pluck(m, d=0.35):
    t = tt(d); f = mtof(m)
    x = (saw(f, t) + 0.6 * np.sin(2 * np.pi * f * t)) * np.exp(-t / 0.09)
    return lp(x, 3200)
def riser(d):
    t = tt(d); x = rng.standard_normal(len(t)); out = np.zeros_like(x); blk = 512
    for i in range(0, len(x), blk):
        fc = 400 + 5000 * (i / len(x)) ** 2
        out[i:i+blk] = bp(x[max(0, i-2048):i+blk], fc * 0.7, min(SR*0.45, fc * 1.5))[-len(x[i:i+blk]):]
    return out * (t / d) ** 2
def swell_down(d):
    t = tt(d); x = hp(rng.standard_normal(len(t)), 2500); return x * np.exp(-t / (d * 0.35)) * np.clip(t / 0.01, 0, 1)

# ---- harmony: Am9 | Fmaj9 | Cmaj9 | G6  (2 bars each), resolve on Cmaj9 ----
CH = [([57, 60, 64, 67, 71], 45), ([53, 57, 60, 64, 67], 41), ([48, 52, 55, 59, 62], 36), ([55, 59, 62, 64, 67], 43)]
TOTALB = int(np.ceil(T / P))
MEET, OSS, END = 8, 60, 68              # film beats: "Meet cresavo", open-source beat, end card
for b0 in range(0, END, 8):
    notes, root = CH[(b0 // 8) % 4]
    bright = 0.25 if b0 < MEET else (0.6 if b0 < OSS else 0.9)
    l, r = pad(notes, bt(8) + 0.5, bright); put(l, bt(b0), 0.16, -0.5); put(r, bt(b0), 0.16, 0.5)
# final resolve: long Cmaj9 with slow fade (the end card)
l, r = pad([48, 55, 59, 62, 64, 67], T - bt(END) + 0.2, 0.7); put(l, bt(END), 0.2, -0.5); put(r, bt(END), 0.2, 0.5)
put(bass(36, 2.6), bt(END), 0.32)

for b in range(TOTALB):
    t0 = bt(b); bar_pos = b % 4
    notes, root = CH[((b // 8) % 4)] if b < END else CH[2]
    if b < MEET:                                      # opening: soft heartbeat pulse + ticking hat, held back
        if b >= 4: put(kick(), t0, 0.35)
        put(hat(), t0 + P / 2, 0.05, 0.3)
        continue
    if b < OSS:                                       # groove
        put(kick(), t0, 0.62)
        put(hat(True), t0 + P / 2, 0.11, 0.25)
        put(hat(), t0 + P / 4, 0.045, -0.3); put(hat(), t0 + 3 * P / 4, 0.045, -0.3)
        if bar_pos in (1, 3): put(clap(), t0, 0.22, 0.05)
        put(bass(root, P * 0.42), t0 + P / 2, 0.34)
        if b % 2 == 1 and b >= 16:                    # sparse plucked arpeggio, chord tones
            put(pluck(notes[(b // 2) % len(notes)] + 12), t0 + P * 0.75, 0.07, 0.4 if b % 4 == 1 else -0.4)
    elif b < END:                                     # open-source breakdown: no kick, lighter hats, pad leads
        put(hat(), t0 + P / 2, 0.05, 0.25)
        if b % 2 == 0: put(bass(root, P * 1.6), t0, 0.22)
        if b >= END - 2: put(kick(), t0, 0.3 * (b - (END - 3)))
    else:                                             # end card: just the resolve
        pass

# "opening-up" moment into Meet cresavo: riser over beats 6–8, a soft downlifter + kick on beat 8
rz = riser(bt(2)); put(rz, bt(MEET - 2), 0.10, 0.0)
put(swell_down(1.6), bt(MEET), 0.05); put(kick(), bt(MEET), 0.55)

mix = np.stack([L, R], 1)
b, a = signal.butter(1, 30 / (SR / 2), 'high'); mix = signal.lfilter(b, a, mix, axis=0)
mix *= np.clip(np.arange(N) / (0.01 * SR), 0, 1)[:, None]
mix = mix / max(1e-9, np.abs(mix).max()) * 0.89
os.makedirs(os.path.join(ROOT, 'out'), exist_ok=True)
wavfile.write(os.path.join(ROOT, 'out', '_music.wav'), SR, (mix * 32767).astype(np.int16))
print('music.py ->', os.path.join(ROOT, 'out', '_music.wav'), round(T, 2), 's, period', P, 'beats', TOTALB)
